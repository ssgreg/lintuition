func TestOutputDestinations(t *testing.T) {
	sample(t)
	for _, args := range [][]string{
		{"--output.text.path", "stdout", "--output.json.path", "stdout"},
		{"--output.json.path", "stderr"},
		{"--output.text.path", "out.txt", "--output.json.path", "./out.txt"},
	} {
		code, out, errs := run(append(append([]string{"run"}, args...), "./...")...)
		if code != 2 || out != "" || !strings.Contains(errs, "output.formats") {
			t.Fatalf("%v: exit %d, out %q, %s", args, code, out, errs)
		}
	}
}

func TestNaNRejected(t *testing.T) {
	dir := sample(t)
	for _, extra := range []string{
		"linters:\n  settings:\n    metric-type-vs-help:\n      threshold: .nan\n",
		"linters:\n  settings:\n    metric-type-vs-help:\n      threshold: .inf\n",
	} {
		os.WriteFile(filepath.Join(dir, "nan.yml"), []byte("version: \"2\"\n"+extra), 0o600)
		if code, _, errs := run("config", "verify", "-c", "nan.yml"); code != 2 || !strings.Contains(errs, "must be a number in (0, 1]") {
			t.Fatalf("%q: exit %d %s", extra, code, errs)
		}
	}
	os.WriteFile(filepath.Join(dir, "nan.yml"), []byte("version: \"2\"\nsemantic:\n  budget:\n    max-cost-usd: .nan\n"), 0o600)
	if code, _, errs := run("config", "verify", "-c", "nan.yml"); code != 2 || !strings.Contains(errs, "finite") {
		t.Fatalf("NaN budget: exit %d %s", code, errs)
	}
}

