// Regressions from the M1 review: each test is one reproduction from it.

func appendConfig(t *testing.T, dir, extra string) {
	t.Helper()
	p := filepath.Join(dir, ".lintuition.yml")
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, append(b, []byte(extra)...), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestGeneratedOutsideBase(t *testing.T) {
	dir := sample(t)
	p := filepath.Join(dir, "metrics.go")
	b, _ := os.ReadFile(p)
	os.WriteFile(p, append([]byte("// Code generated by review. DO NOT EDIT.\n\n"), b...), 0o600)
	for _, wd := range []string{dir, filepath.Join(dir, "sub")} {
		os.MkdirAll(wd, 0o700)
		t.Chdir(wd)
		pattern := "./..."
		if wd != dir {
			pattern = "../"
		}
		if code, _, errs := run("run", pattern); code != 0 || !strings.Contains(errs, "0 asked") || !strings.Contains(errs, "4 skipped") {
			t.Fatalf("from %s: exit %d, %s", wd, code, errs)
		}
	}
}

func TestRelativeConfigPathCfgMode(t *testing.T) {
	dir := sample(t)
	appendConfig(t, dir, "run:\n  relative-path-mode: cfg\n")
	os.MkdirAll(filepath.Join(dir, "sub"), 0o700)
	for _, cfg := range []string{"../.lintuition.yml", filepath.Join(dir, ".lintuition.yml")} {
		t.Chdir(filepath.Join(dir, "sub"))
		_, out, errs := run("run", "-c", cfg, "--output.json.path", "stdout", "../")
		var rep struct {
			Issues []struct{ Pos struct{ Filename string } }
		}
		if err := json.Unmarshal([]byte(out), &rep); err != nil || len(rep.Issues) != 1 || rep.Issues[0].Pos.Filename != "metrics.go" {
			t.Fatalf("-c %s: %v %s %s", cfg, err, out, errs)
		}
	}
}

func TestOutputOptions(t *testing.T) {
	dir := sample(t)
	appendConfig(t, dir, "output:\n  show-stats: false\n")
	if code, _, errs := run("run", "./..."); code != 1 || errs != "" {
		t.Fatalf("show-stats false: exit %d, stderr %q", code, errs)
	}
	for _, key := range []string{"output:\n  sort-order: [file]\n", "run:\n  concurrency: 4\n", "output:\n  formats:\n    text:\n      colors: true\n"} {
		os.WriteFile(filepath.Join(dir, ".lintuition.yml"), []byte("version: \"2\"\n"+key), 0o600)
		if code, _, errs := run("config", "verify"); code != 2 || !strings.Contains(errs, "not found") {
			t.Fatalf("%q must be rejected until implemented: exit %d %s", key, code, errs)
		}
	}
}

